import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROPOSED_PATH = join(ROOT, 'docs', 'motorrad-proposed-scoring-profiles.json');
const AUDIT_PATH = join(ROOT, 'docs', 'motorrad-scoring-field-audit.json');
const RUNTIME_PATH = join(ROOT, 'server', 'data', 'motorrad-runtime-scoring-profiles.js');
const RUNTIME_FIELDS = ['category', 'fuel', 'sizeClass', 'tags', 'defaultCc', 'factoryKw', 'kerbMassKg', 'powerToWeightKwPerKg', 'zeroTo62', 'mpg', 'evRange', 'seats', 'boot'];
const EXPLANATION_FIELDS = new Set(['category', 'fuel', 'tags', 'mpg']);
const VALID_PROVENANCE = new Set(['sourced', 'calculated', 'editorial', 'unavailable']);

export function buildRuntimeScoringProfiles(proposed, audit) {
  const auditById = new Map(audit.records.map((record) => [record.canonicalDerivativeId, record]));
  const profiles = proposed.profiles.map((profile) => {
    const fields = Object.fromEntries(RUNTIME_FIELDS.map((field) => {
      const proposal = profile.fields[field];
      return [field, { value: proposal.value, provenance: proposal.provenance, explanationEligible: EXPLANATION_FIELDS.has(field) && proposal.provenance !== 'unavailable' }];
    }));
    return { canonicalDerivativeId: profile.canonicalDerivativeId, recordType: profile.recordType, compatibilityProfile: profile.compatibilityProfile, fields };
  }).sort((a, b) => a.canonicalDerivativeId.localeCompare(b.canonicalDerivativeId));
  const runtime = { schemaVersion: 1, profiles };
  validateRuntimeScoringProfiles(runtime, proposed, auditById);
  return runtime;
}

export function validateRuntimeScoringProfiles(runtime, proposed, auditOrMap) {
  const auditById = auditOrMap instanceof Map ? auditOrMap : new Map(auditOrMap.records.map((record) => [record.canonicalDerivativeId, record]));
  if (!Array.isArray(runtime.profiles) || runtime.profiles.length !== 107 || proposed.profiles.length !== 107 || auditById.size !== 107) throw new Error('runtime scoring profile count mismatch');
  const ids = new Set();
  for (const profile of runtime.profiles) {
    if (!profile.canonicalDerivativeId || ids.has(profile.canonicalDerivativeId)) throw new Error(`duplicate runtime scoring ID: ${profile.canonicalDerivativeId}`);
    ids.add(profile.canonicalDerivativeId);
    const source = proposed.profiles.find((item) => item.canonicalDerivativeId === profile.canonicalDerivativeId);
    const audit = auditById.get(profile.canonicalDerivativeId);
    if (!source || !audit) throw new Error(`unknown runtime scoring source: ${profile.canonicalDerivativeId}`);
    for (const field of RUNTIME_FIELDS) {
      const value = profile.fields?.[field]; const proposal = source.fields[field];
      if (!value || !VALID_PROVENANCE.has(value.provenance) || value.provenance !== proposal?.provenance || JSON.stringify(value.value) !== JSON.stringify(proposal?.value)) throw new Error(`runtime scoring field drift: ${profile.canonicalDerivativeId}/${field}`);
      if (value.provenance === 'unavailable' && value.value !== null) throw new Error(`unsupported runtime value: ${profile.canonicalDerivativeId}/${field}`);
      if ((value.provenance === 'sourced' || value.provenance === 'calculated') && !proposal.evidence?.sourceUrl && !proposal.inputs?.sourceUrl && !proposal.inputs?.massSourceUrl) throw new Error(`missing evidence: ${profile.canonicalDerivativeId}/${field}`);
    }
    if (typeof profile.fields.category.value !== 'string' || typeof profile.fields.fuel.value !== 'string' || !Number.isInteger(profile.fields.sizeClass.value) || !Array.isArray(profile.fields.tags.value)) throw new Error(`unsupported scoring types: ${profile.canonicalDerivativeId}`);
  }
  return true;
}

export function renderRuntimeScoringProfiles(runtime) {
  return `// Generated by scripts/build-motorrad-runtime-scoring-profiles.mjs. Do not edit.\nexport const MOTORRAD_RUNTIME_SCORING_PROFILES = Object.freeze(${JSON.stringify(runtime, null, 2)});\n`;
}

export function runtimeScoringProfilesMatchGenerated(proposedPath = PROPOSED_PATH, auditPath = AUDIT_PATH, runtimePath = RUNTIME_PATH) {
  const proposed = JSON.parse(readFileSync(proposedPath, 'utf8')); const audit = JSON.parse(readFileSync(auditPath, 'utf8'));
  const expected = renderRuntimeScoringProfiles(buildRuntimeScoringProfiles(proposed, audit));
  try { return readFileSync(runtimePath, 'utf8') === expected; } catch { return false; }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const proposed = JSON.parse(readFileSync(PROPOSED_PATH, 'utf8')); const audit = JSON.parse(readFileSync(AUDIT_PATH, 'utf8'));
  const rendered = renderRuntimeScoringProfiles(buildRuntimeScoringProfiles(proposed, audit));
  if (process.argv.includes('--check')) {
    if (readFileSync(RUNTIME_PATH, 'utf8') !== rendered) throw new Error('Motorrad runtime scoring profiles drift; run npm run build:motorrad-scoring-runtime');
    console.log('Motorrad runtime scoring profiles are current.');
  } else {
    mkdirSync(dirname(RUNTIME_PATH), { recursive: true });
    writeFileSync(RUNTIME_PATH, rendered);
    console.log(`Wrote ${RUNTIME_PATH}`);
  }
}
