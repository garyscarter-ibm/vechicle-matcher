import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { MODEL_SPECS_MOTORRAD } from '../server/mapping.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_PATH = join(ROOT, 'docs', 'motorrad-derivative-catalogue.json');
const RUNTIME_PATH = join(ROOT, 'server', 'data', 'motorrad-runtime-catalogue.js');
export function buildRuntimeCatalogue(reviewedCatalogue, profileSpecs = MODEL_SPECS_MOTORRAD) {
  if (!reviewedCatalogue?.records || !Array.isArray(reviewedCatalogue.records)) throw new TypeError('Reviewed derivative catalogue is required');
  const records = reviewedCatalogue.records.map((record) => ({
    sourceRecordId: record.canonicalDerivativeId,
    canonicalDerivativeId: record.canonicalDerivativeId,
    recordType: record.recordType,
    modelFamily: record.modelFamily,
    derivativeTrim: record.derivativeTrim,
    compatibilityProfile: record.comparisonProfileKey || null,
    resolver: record.resolver,
  })).sort((a, b) => a.canonicalDerivativeId.localeCompare(b.canonicalDerivativeId));
  const runtime = Object.freeze({ schemaVersion: 1, records });
  validateRuntimeCatalogue(runtime, reviewedCatalogue, profileSpecs);
  return runtime;
}

export function validateRuntimeCatalogue(runtime, reviewedCatalogue, profileSpecs = MODEL_SPECS_MOTORRAD) {
  const sourceIds = new Set(reviewedCatalogue.records.map((record) => record.canonicalDerivativeId));
  const ids = new Set();
  for (const record of runtime.records || []) {
    if (!record.canonicalDerivativeId || ids.has(record.canonicalDerivativeId)) throw new Error(`duplicate/missing runtime derivative ID: ${record.canonicalDerivativeId}`);
    ids.add(record.canonicalDerivativeId);
    if (!sourceIds.has(record.sourceRecordId) || record.sourceRecordId !== record.canonicalDerivativeId) throw new Error(`runtime record has unknown source: ${record.canonicalDerivativeId}`);
    if (!record.resolver || !Array.isArray(record.resolver.modelAliases) || !Array.isArray(record.resolver.derivativeAliases) || !Array.isArray(record.resolver.advertisedCc) || !Array.isArray(record.resolver.advertisedPowerKw)) throw new Error(`missing resolver metadata: ${record.canonicalDerivativeId}`);
    if (record.recordType === 'derivative' && !record.resolver.identityAnchor) {
      if (!record.compatibilityProfile || !profileSpecs[record.compatibilityProfile]) throw new Error(`unknown compatibility profile: ${record.canonicalDerivativeId} -> ${record.compatibilityProfile}`);
    } else if (record.compatibilityProfile && !profileSpecs[record.compatibilityProfile]) throw new Error(`unknown runtime profile: ${record.canonicalDerivativeId} -> ${record.compatibilityProfile}`);
  }
  if (ids.size !== sourceIds.size) throw new Error(`runtime/source record count mismatch: ${ids.size}/${sourceIds.size}`);
  return true;
}

export function renderRuntimeCatalogue(runtime) {
  return `// Generated by scripts/build-motorrad-runtime-catalogue.mjs. Do not edit.\nexport const MOTORRAD_RUNTIME_CATALOGUE = Object.freeze(${JSON.stringify(runtime, null, 2)});\n`;
}

export function runtimeCatalogueMatchesGenerated(source = SOURCE_PATH, runtimePath = RUNTIME_PATH) {
  const reviewed = JSON.parse(readFileSync(source, 'utf8'));
  const expected = renderRuntimeCatalogue(buildRuntimeCatalogue(reviewed));
  let actual = null;
  try { actual = readFileSync(runtimePath, 'utf8'); } catch { return false; }
  return actual === expected;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const reviewed = JSON.parse(readFileSync(SOURCE_PATH, 'utf8'));
  const rendered = renderRuntimeCatalogue(buildRuntimeCatalogue(reviewed));
  if (process.argv.includes('--check')) {
    if (readFileSync(RUNTIME_PATH, 'utf8') !== rendered) throw new Error('Motorrad runtime catalogue drift; run npm run build:motorrad-runtime');
    console.log('Motorrad runtime catalogue is current.');
  } else {
    mkdirSync(dirname(RUNTIME_PATH), { recursive: true });
    writeFileSync(RUNTIME_PATH, rendered);
    console.log(`Wrote ${RUNTIME_PATH}`);
  }
}
